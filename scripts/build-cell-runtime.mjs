import { readFile, writeFile } from "node:fs/promises";
import ts from "typescript";
import { format } from "prettier";

// Capture canonical source before a deploy bundler can inject name helpers or rename
// closure dependencies. The generated string literals are safe to bundle/minify.
const root = new URL("../", import.meta.url);
const sources = {};
for (const [file, names] of [
  ["packages/core/src/codec.ts", ["encodeGraph", "decodeGraph"]],
  ["packages/core/src/compiler.ts", ["hardenCellGlobals"]],
]) {
  const text = await readFile(new URL(file, root), "utf8");
  const ast = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true);
  for (const name of names) {
    const declaration = ast.statements.find(
      (node) => ts.isFunctionDeclaration(node) && node.name?.text === name,
    );
    if (!declaration) throw new Error(`Missing runtime function ${name} in ${file}`);
    const plain = ts.factory.updateFunctionDeclaration(
      declaration,
      undefined,
      declaration.asteriskToken,
      declaration.name,
      declaration.typeParameters,
      declaration.parameters,
      declaration.type,
      declaration.body,
    );
    const printed = ts.createPrinter().printNode(ts.EmitHint.Unspecified, plain, ast);
    sources[name] = ts
      .transpileModule(printed, {
        compilerOptions: {
          target: ts.ScriptTarget.ES2022,
          module: ts.ModuleKind.ESNext,
          removeComments: true,
        },
      })
      .outputText.trim();
  }
}
const output = await format(
  `// Generated by scripts/build-cell-runtime.mjs. Edit the canonical functions, then run npm run runtime:generate.\nexport const cellRuntimeSources = ${JSON.stringify(sources, null, 2)} as const;\n`,
  { parser: "typescript" },
);
const destination = new URL("packages/core/src/runtime-source.ts", root);
if (process.argv.includes("--check")) {
  const current = await readFile(destination, "utf8").catch(() => "");
  if (current !== output)
    throw new Error(
      "Cell runtime source is stale. Run npm run runtime:generate and commit the generated file.",
    );
} else await writeFile(destination, output);
